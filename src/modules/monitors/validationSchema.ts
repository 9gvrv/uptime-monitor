import { z } from "zod";
import { ERROR_TYPES } from "../../lib/checkWebsite.js";

// Shared field schemas: create, update and the public "try" endpoint must all
// reject the same bad input. Lengths mirror the DB columns (varchar(100) /
// varchar(2048)) so validation failures never surface as database errors.
export const monitorNameSchema = z.string().trim().min(1).max(100);

export const monitorUrlSchema = z.url().max(2048).refine(
  (value) => {
    const { protocol } = new URL(value);
    return protocol === "http:" || protocol === "https:";
  },
  { message: "Only http(s) URLs are allowed" },
);

// Input schema for creating a monitor. `id` is generated by the database,
// so clients must not supply it (and it is not required here).
export const registerMonitorSchema = z.object({
  name: monitorNameSchema,
  url: monitorUrlSchema,
});

// Input schema for updating a monitor. Only known fields are accepted, so a
// caller cannot change userId, id, groupId or timestamps through this route.
export const updateMonitorSchema = registerMonitorSchema.partial().extend({
  isActive: z.boolean().optional(),
});

// Response schema for a monitor. Kept separate from the input schema so the
// database-generated `id` (and other returned columns) are included in replies.
export const ReturnMonitor = z.object({
  id: z.number().positive(),
  name: z.string(),
  url: z.string().url(),
  isActive: z.boolean(),
  groupId: z.number().positive().nullable(),
  createdAt: z.date(),
  updatedAt: z.date(),
});

export const freeHealthCheckSchema = z.object({
  url: monitorUrlSchema,
});

export const ReturnHealthCheck = z.object({
  id: z.number().positive(),
  monitorId: z.number().positive(),
  status: z.enum(["up", "down", "degraded"]),
  statusCode: z.number().positive().nullable(),
  finalUrl: z.string().nullable(),
  redirectCount: z.number().int().nonnegative(),
  ttfbMs: z.number().int().nonnegative().nullable(),
  totalMs: z.number().int().nonnegative(),
  errorType: z.enum(ERROR_TYPES).nullable(),
  errorMessage: z.string().nullable(),
  region: z.string().nullable(),
  checkedAt: z.date(),
});
